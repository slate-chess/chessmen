"""Builds PGN Replay piece sets from the app's piece artwork, so the web board and the app match.

  python3 tools/build_pieces.py --app /path/to/the/app/source   (or set SLATE_APP)

Reads Shared/PieceSets.xcassets/<prefix>_<white|black>_<piece>.imageset/*.svg (the untinted base
set) and writes src/pieces/<name>.js, an ES module exporting the set. `npm run build` turns each
into dist/pieces/<name>.js (a script that registers it) and dist/pieces/<name>.mjs.
Only sets whose licence allows redistribution belong here; record each in THIRD-PARTY-NOTICES.md.
"""
import argparse, json, os, re

SETS = {
    # name: (asset prefix, display name, licence, credit)
    "modern-staunton": ("cburnett", "Modern Staunton", "BSD-3-Clause",
                        "after the chess pieces by Colin M. L. Burnett (2006)"),
    "classic-staunton": ("merida", "Classic Staunton", "Unlicense",
                         "after Chess Mérida by Armando Hernández Marroquín (1998)"),
}
PIECES = {"king": "K", "queen": "Q", "rook": "R", "bishop": "B", "knight": "N", "pawn": "P"}
ROOT_ATTRS = ("fill", "fill-rule", "clip-rule", "stroke", "stroke-width")


def piece(path):
    svg = open(path, encoding="utf-8").read()
    head = re.search(r"<svg\b([^>]*)>", svg)
    attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', head.group(1)))
    body = svg[head.end():svg.rindex("</svg>")].strip()
    keep = {k: attrs[k] for k in ROOT_ATTRS if k in attrs}
    m = re.search(r"fill:\s*(#[0-9a-fA-F]+)", attrs.get("style", ""))
    if m and "fill" not in keep:
        keep["fill"] = m.group(1)            # cburnett sets its default fill in a style attribute
    if keep:
        body = "<g " + " ".join(f'{k}="{v}"' for k, v in keep.items()) + ">" + body + "</g>"
    if re.search(r'\sid="', body):
        raise SystemExit(f"{path}: ids inside a piece would clash between boards")
    return {"viewBox": attrs["viewBox"], "body": body}


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--app", default=os.environ.get("SLATE_APP"), required="SLATE_APP" not in os.environ,
                    help="the Slate Chess app's source folder (or set SLATE_APP)")
    a = ap.parse_args()
    assets = os.path.join(a.app, "Shared", "PieceSets.xcassets")
    for name, (prefix, label, licence, credit) in SETS.items():
        pieces = {}
        for colour, c in (("white", "w"), ("black", "b")):
            for p, letter in PIECES.items():
                d = os.path.join(assets, f"{prefix}_{colour}_{p}.imageset")
                svg = next(f for f in os.listdir(d) if f.endswith(".svg"))
                pieces[c + letter] = piece(os.path.join(d, svg))
        out = os.path.join(here, "..", "src", "pieces", f"{name}.js")
        meta = {"name": name, "label": label, "licence": licence, "credit": credit}
        with open(out, "w", encoding="utf-8") as f:
            f.write(f"/*! PGN Replay piece set: {label}, {credit}. Licence: {licence} (see THIRD-PARTY-NOTICES.md).\n"
                    f" * Generated by tools/build_pieces.py from the Slate Chess app's artwork. Do not edit. */\n")
            f.write("export default " + json.dumps({**meta, "pieces": pieces}, ensure_ascii=False) + ";\n")
        print(f"{name}: {os.path.getsize(out):,} bytes")


if __name__ == "__main__":
    main()
